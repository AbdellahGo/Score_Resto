    <p>Siège social : 2, avenue Saint Julien, 08000 Charleville-Mézières</p>
    <p>Directeur de la publication : Valdo Sallairoie</p>
    <p>Responsable technique application : Jack Moba</p>
    <p>Responsable technique hébergement : Alfred Van Vogt</p>
    <p>Contact administratif : Caroline Slans</p>

    <h2>Article 4 – Accès au site</h2>
    <p>Le site est accessible :</p>
    <ul>
        <li>aux visiteurs non authentifiés,</li>
        <li>aux utilisateurs authentifiés.</li>
    </ul>
    <p>
        Certaines fonctionnalités sont réservées aux utilisateurs enregistrés.
    </p>

    <h2>Article 5 – Inscription et compte utilisateur</h2>
    <p>L’inscription est gratuite.</p>
    <p>L’utilisateur s’engage à :</p>
    <ul>
        <li>fournir des informations exactes,</li>
        <li>protéger ses identifiants,</li>
        <li>ne pas utiliser le compte d’un autre utilisateur.</li>
    </ul>

    <h2>Article 6 – Fonctionnalités du site</h2>

    <h3>a) Pour les visiteurs</h3>
    <ul>
        <li>rechercher des restaurants,</li>
        <li>consulter les fiches restaurants,</li>
        <li>lire les avis et notes,</li>
        <li>s’inscrire sur le site.</li>
    </ul>

    <h3>b) Pour les utilisateurs authentifiés</h3>
    <ul>
        <li>rechercher des restaurants,</li>
        <li>aimer des restaurants,</li>
        <li>noter des restaurants,</li>
        <li>publier des avis et commentaires,</li>
        <li>consulter les avis des autres utilisateurs,</li>
        <li>personnaliser son profil.</li>
    </ul>

    <h2>Article 7 – Avis et commentaires</h2>
    <p>Les avis doivent être :</p>
    <ul>
        <li>respectueux,</li>
        <li>objectifs,</li>
        <li>conformes à la loi.</li>
    </ul>
    <p>Le site se réserve le droit de :</p>
    <ul>
        <li>supprimer un avis,</li>
        <li>suspendre ou supprimer un compte en cas d’abus.</li>
    </ul>

    <h2>Article 8 – Responsabilité</h2>
    <p>Le site n’est pas responsable :</p>
    <ul>
        <li>du contenu des avis publiés par les utilisateurs,</li>
        <li>des conséquences liées à l’utilisation du site.</li>
    </ul>

    <h2>Article 9 – Données personnelles</h2>
    <p>
        Les données personnelles sont collectées uniquement pour le fonctionnement du site.
    </p>
    <p>Conformément au RGPD, l’utilisateur peut :</p>
    <ul>
        <li>accéder à ses données,</li>
        <li>les modifier,</li>
        <li>demander leur suppression.</li>
    </ul>

    <h2>Article 10 – Modification des CGU</h2>
    <p>
        Le site peut modifier les CGU à tout moment.
        Les nouvelles CGU s’appliquent dès leur publication.
    </p>

    <h2>Article 11 – Droit applicable</h2>
    <p>Les présentes CGU sont soumises au droit français.</p>

