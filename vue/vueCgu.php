    <h1>Conditions Générales d’Utilisation (CGU)</h1>
    <p><strong>Site :</strong> www.scoreresto.fr</p>

    <h2>Article 1 – Objet des CGU</h2>
    <p>
        Les présentes Conditions Générales d’Utilisation ont pour objectif de définir
        les règles d’accès et d’utilisation du site www.scoreresto.fr.
    </p>
    <p>
        Toute utilisation du site implique l’acceptation complète des CGU.
    </p>

    <h2>Article 2 – Présentation du site</h2>
    <p>Le site Score Resto est une plateforme permettant :</p>
    <ul>
        <li>de rechercher des restaurants,</li>
        <li>de consulter leurs informations,</li>
        <li>de lire des avis et notes,</li>
        <li>de publier des avis pour les utilisateurs enregistrés.</li>
    </ul>

    <h2>Article 3 – Éditeur du site</h2>
    <p>
        Le site est édité par la société <strong>Haissiho</strong>, propriété de
        <strong>Valdo Sallairoie</strong>.
